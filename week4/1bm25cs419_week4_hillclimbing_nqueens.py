import random

def conflicts(board):
    n = len(board)
    count = 0
    for i in range(n):
        for j in range(i + 1, n):
            if board[i] == board[j] or abs(board[i] - board[j]) == j - i:
                count += 1
    return count

def hill_climbing(n):
    for restart in range(100):
        board = [random.randrange(n) for _ in range(n)]

        for step in range(1000):
            if conflicts(board) == 0:
                return board, restart + 1, step

            col = random.choice([
                c for c in range(n)
                if any(
                    board[c] == board[j] or
                    abs(board[c] - board[j]) == abs(c - j)
                    for j in range(n) if j != c
                )
            ])

            scores = []
            for row in range(n):
                old = board[col]
                board[col] = row
                scores.append(conflicts(board))
                board[col] = old

            best = min(scores)
            choices = [r for r in range(n) if scores[r] == best]
            board[col] = random.choice(choices)

    return None, 100, 1000

n = int(input("Enter N: "))

if n < 1:
    print("Enter a positive integer.")
else:
    solution, restarts, steps = hill_climbing(n)

    if solution:
        print("Solution:", solution)
        print("Conflicting pairs:", conflicts(solution))
        print("Restarts:", restarts)
        print("Steps:", steps)
    else:
        print("Solution not found.")